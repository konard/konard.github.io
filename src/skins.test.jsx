import { act, render } from '@testing-library/react';
import { readFileSync } from 'node:fs';
import { afterEach, describe, expect, it } from 'vitest';
import LiquidRefraction from './components/LiquidRefraction';
import { FIELDS, PALETTES } from './settings/schema';
import { setSettings } from './settings/store';

const css = (file) => readFileSync(new URL(file, import.meta.url), 'utf8');
const liquid = css('./skins.liquid.css') + css('./skins.materials.css');
const glass = css('./skins.glass.css') + css('./index.css') + css('./App.css') + css('./Layout.css');
const future = css('./skins.future.css') + css('./skins.palettes.css') + css('./skins.frames.css');
const name = (key) => key.replace(/\./g, '-').replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

// Choices that mean "no extra style", so no rule is needed for them.
// Choices that are the plain skin. Corner marks and a gradient surface were the
// defaults before issue #45 and still need no rule of their own.
const NOTHING = {
  'future.hover': ['none'],
  'future.title': ['plain'],
  'glass.shadow': ['none'],
  'future.frame': ['corners'],
  'future.surface': ['gradient'],
};
// Numbers used by the SVG filter or generated static grain, not a stylesheet.
const IN_JSX = [
  'liquid.noise',
  'liquid.refractionScale',
  'liquid.refractionDetail',
  'liquid.refractionOctaves',
  'liquid.refractionSmoothing',
  'liquid.refractionSeed',
];

describe.each([
  ['liquid', liquid, 15],
  ['future', future, 15],
  ['glass', glass, 8],
])('the %s skin (issues #13 and #15)', (prefix, sheet, many) => {
  const fields = FIELDS.filter((f) => f.key.startsWith(`${prefix}.`));

  it('has many settings', () => {
    expect(fields.length).toBeGreaterThanOrEqual(many);
  });

  it.each(fields.filter((f) => f.type === 'range' && !IN_JSX.includes(f.key)).map((f) => f.key))(
    'uses the number %s',
    (key) => {
      expect(sheet).toContain(`var(--${name(key)}`);
    },
  );

  it.each(fields.filter((f) => f.type !== 'range').map((f) => f.key))('has a style for every choice of %s', (key) => {
    const f = FIELDS.find((x) => x.key === key);
    if (f.type === 'toggle') {
      // A switch needs a rule for one of its states; the other is the plain skin.
      expect(sheet).toMatch(new RegExp(`\\[data-${name(key)}='(true|false)'\\]`));
      return;
    }
    const values = f.options.map((o) => o.value).filter((v) => v !== f.d);
    for (const value of values.filter((v) => !NOTHING[key]?.includes(v))) {
      expect(sheet, `${key} = ${value}`).toContain(`[data-${name(key)}='${value}']`);
    }
  });
});

describe('futuristic palettes (issue #13)', () => {
  it.each(PALETTES.map(([id]) => id))('%s has dark and light colours', (id) => {
    const rule = `:root[data-skin-name='futuristic'][data-future-palette='${id}']`;
    expect(future).toContain(`${rule} {`);
    expect(future).toContain(`${rule}[data-theme='light'] {`);
  });

  it('match the generator in experiments/', () => {
    // skins.palettes.css is generated by experiments/future-palettes.mjs.
    expect(css('./skins.palettes.css')).toMatch(/--fx-neon-rgb: 126 252 246;/);
  });
});

describe('liquid refraction (issue #13)', () => {
  const root = document.documentElement;
  afterEach(() => {
    delete navigator.userAgentData;
    act(() => setSettings({ 'skin.name': 'glass', 'liquid.refraction': false }));
  });

  it('renders the SVG filter with the chosen strength and marks <html> in Chromium', () => {
    navigator.userAgentData = { brands: [] };
    act(() =>
      setSettings({
        'skin.name': 'liquid',
        'liquid.refraction': true,
        'liquid.refractionScale': 60,
        'liquid.refractionDetail': 20,
      }),
    );
    const { container, unmount } = render(<LiquidRefraction />);
    expect(container.querySelector('filter#liquid-refraction')).toBeInTheDocument();
    expect(container.querySelector('feDisplacementMap')).toHaveAttribute('scale', '60');
    expect(container.querySelector('feTurbulence')).toHaveAttribute('baseFrequency', '0.02');
    expect(root.dataset.refracts).toBe('');
    act(() => setSettings({ 'liquid.refraction': false }));
    expect(container.querySelector('filter')).toBeNull();
    expect(root.dataset.refracts).toBeUndefined();
    unmount();
  });

  it('renders nothing where backdrop filters cannot use SVG (Safari, Firefox)', () => {
    act(() => setSettings({ 'skin.name': 'liquid', 'liquid.refraction': true }));
    const { container } = render(<LiquidRefraction />);
    expect(container.querySelector('filter')).toBeNull();
    expect(root.dataset.refracts).toBeUndefined();
  });

  it('renders nothing with another skin', () => {
    navigator.userAgentData = { brands: [] };
    act(() => setSettings({ 'skin.name': 'futuristic', 'liquid.refraction': true }));
    const { container } = render(<LiquidRefraction />);
    expect(container.querySelector('filter')).toBeNull();
  });
});

describe('the glass skin (issue #15)', () => {
  const panels = (sheet, from) => {
    const start = sheet.indexOf(':is(', sheet.indexOf(from));
    return sheet
      .slice(start + 4, sheet.indexOf(')', start))
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);
  };

  it('puts the glass on the same panels as the other skins', () => {
    const list = panels(future, '/* ---------- Panels ---------- */');
    expect(list.length).toBeGreaterThan(20);
    expect(panels(glass, '@media screen')).toEqual(list);
    expect(panels(liquid, '/* Panels, cards and tiles of every page. */')).toEqual(list);
  });
});

describe('percent settings (issue #15)', () => {
  // A range in percents above 2 (`glass.saturation` = 100) is written to CSS as
  // a bare number, so it must be divided by 100: `saturate(100)` is 10 000 %
  // and painted every glass panel blue.
  const sheets = [
    './index.css',
    './App.css',
    './Layout.css',
    './skins.glass.css',
    './skins.liquid.css',
    './skins.future.css',
  ]
    .map(css)
    .join('\n');
  const percents = FIELDS.filter((f) => f.type === 'range' && f.unit === '%' && f.max > 2);

  it.each(percents.map((f) => f.key))('divides %s by 100 wherever it is used', (key) => {
    const uses = [...sheets.matchAll(new RegExp(`var\\(--${name(key)}[^)]*\\)\\s*(/\\s*100)?`, 'g'))];
    expect(uses.length).toBeGreaterThan(0);
    for (const use of uses) expect(use[0], key).toMatch(/\/\s*100$/);
  });
});
