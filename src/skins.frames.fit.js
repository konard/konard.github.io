// Corners of the frame by the size of the element (issue #47: "we should be
// able to configure CORNERS OF THE FRAME based on conditions like
// minimum/maximum height/width of the UI element").
//
// Every level of the frame (outer panels, inner blocks and every type of
// control) has a minimum and a maximum width and height; an element of the
// level outside them draws its corners in their size times the fit scale of
// the level (0: no corners, a plain rectangle).
//
// A stylesheet cannot select an element by its own size: container queries ask
// about an ancestor. So src/frameFit.js measures the elements of the levels
// with limits (one ResizeObserver, only while a level has limits) and marks
// those outside them with `data-fx-fit="<level>"`, and this stylesheet
// (src/skins.frames.fit.css, `npm run build:frames`) draws a marked element
// from the same lengths of the root, each one times the fit scale. The other
// elements of the page draw as before and cost nothing more.
//
// It imports only src/skins.frames.js, so a plain Node script can run it.
import {
  CONTROL_TYPES,
  clip,
  controlsOf,
  element,
  FRAME,
  layers,
  ownCorners,
  sameCorners,
  STRONG,
} from './skins.frames.js';

/** The levels of the frame, as in the corners section of the settings. */
export const FIT_LEVELS = ['panel', 'block', ...Object.keys(CONTROL_TYPES)];

/** The attribute that marks an element outside the limits of its level. */
export const FIT_ATTR = 'data-fx-fit';

/** The fit scale of a level, a variable of the root (`corner.fitScale`, `corner.buttonFitScale`…). */
export const fitScale = (level) => `var(--corner-${level === 'panel' ? '' : `${level}-`}fit-scale, 1)`;

/**
 * `css` with every length of a corner in scale `k` (`--fxp-tl-x`,
 * `--fxbutton-br-arm`…) times `factor`. The widths of the edges
 * (`--fxp-ew-top`) stay, so a frame without corners keeps its edges.
 */
export const scaled = (css, k, factor) =>
  css.replace(new RegExp(`var\\(--fx${k}-(?:tl|tr|br|bl)-[\\w-]+\\)`, 'g'), (length) => `calc(${length} * ${factor})`);

const scaledAll = (declarations, k, factor) =>
  Object.fromEntries(Object.entries(declarations).map(([name, value]) => [name, scaled(value, k, factor)]));

/** A marked element of `level`, one attribute: (0,1,0) above the rule it overrides. */
const marked = (level) => `[${FIT_ATTR}='${level}']`;

/** A rule with the long lists of layers on one line each. */
const rule = (selector, declarations) =>
  `${selector} {\n${Object.entries(declarations)
    .map(([name, value]) => `  ${name}: ${value.replace(/\s*\n\s*/g, ' ')};`)
    .join('\n')}\n}\n`;

/** What a control draws in scale `k`: the background layers over its own image, and the outline. */
const control = (k) => ({
  'background-image': `${layers(k)
    .map((layer) => layer[0])
    .join(', ')}, var(--fx-control-img, none)`,
  'background-size': `${layers(k)
    .map((layer) => layer[1])
    .join(', ')}, 100% 100%`,
  'background-position': `${layers(k)
    .map((layer) => layer[2])
    .join(', ')}, 0 0`,
  'clip-path': clip(k),
});

/** The stylesheet of the marked elements (src/skins.frames.fit.css). */
export function fitCss() {
  const out = [
    '/* Generated by src/skins.frames.fit.js (npm run build:frames); do not edit.\n' +
      '   Corners of the frame by the size of the element (issue #47): an element that\n' +
      '   src/frameFit.js marks as outside the limits of its level draws its corners\n' +
      '   times the fit scale of the level. Each rule is one attribute above the rule\n' +
      '   of the frame it overrides. */\n',
    // Outer panels and inner blocks draw with --fx-el-*, which the corner layer above the content inherits.
    rule(`${FRAME} ${marked('panel')}`, scaledAll(element('p'), 'p', fitScale('panel'))),
    rule(`${FRAME} ${marked('block')}`, scaledAll(element('b'), 'b', fitScale('block'))),
    rule(`${FRAME}${ownCorners('block')} ${marked('block')}`, scaledAll(element('block'), 'block', fitScale('block'))),
  ];
  // Controls with the corners of the outer panels in the control scale, and with their own.
  Object.keys(CONTROL_TYPES).forEach((type) => {
    out.push(
      rule(
        controlsOf(type, `${STRONG}${sameCorners(type)}`, marked(type)),
        scaledAll(control('c'), 'c', fitScale(type)),
      ),
      rule(
        controlsOf(type, `${STRONG}${ownCorners(type)}`, marked(type)),
        scaledAll(control(type), type, fitScale(type)),
      ),
    );
  });
  return out.join('\n');
}
