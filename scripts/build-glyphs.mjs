#!/usr/bin/env node
// Enumerates every configuration of 1–4 doublet links (1 + 10 + 129 + 2836)
// and writes:
//   src/links/configurations.json — canonical codes, so the browser never
//                                   enumerates 4^8 variants itself;
//   public/link-glyphs.svg        — a sprite with one same-size symbol per
//                                   configuration (`<use href="#links-2-01-10">`).
// Usage: node scripts/build-glyphs.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { configurations, decode } from '../src/links/configurations.js';
import { glyphId, glyphSymbol } from '../src/links/glyph.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

export function buildGlyphs({ write = true } = {}) {
  const codes = {};
  for (let n = 1; n <= 4; n++) codes[n] = configurations(n);
  const symbols = Object.values(codes)
    .flat()
    .map((code) => glyphSymbol(decode(code), glyphId(code)));
  const sprite =
    '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n' +
    `<!-- ${symbols.length} link configurations, generated by scripts/build-glyphs.mjs -->\n` +
    symbols.join('\n') +
    '\n</svg>\n';
  const json = JSON.stringify(codes) + '\n';
  if (write) {
    fs.writeFileSync(path.join(root, 'src/links/configurations.json'), json);
    fs.writeFileSync(path.join(root, 'public/link-glyphs.svg'), sprite);
  }
  return { codes, sprite, json };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { codes, sprite } = buildGlyphs();
  const counts = Object.values(codes).map((c) => c.length);
  console.log(`configurations ${counts.join(' + ')}, sprite ${Math.round(sprite.length / 1024)} KiB`);
}
