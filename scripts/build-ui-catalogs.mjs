// Keep Node consumers (CV/build configuration) and browser consumers identical.
import { readFile, writeFile } from 'node:fs/promises';
import { readCatalogs } from '@link-foundation/ui-i18n';
const texts = await Promise.all(['en', 'ru'].map((lang) => readFile(`src/i18n/catalogs/${lang}.lino`, 'utf8')));
const catalogs = Object.assign({}, ...texts.map(readCatalogs));
await writeFile(
  'src/i18n/catalogs.generated.js',
  `// Generated by npm run build:i18n from catalogs/*.lino.\nexport default JSON.parse(${JSON.stringify(JSON.stringify(catalogs))});\n`,
);
