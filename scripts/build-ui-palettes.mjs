// Compile the site's theme pack with the framework's token resolver. The RGB
// channel bridge keeps existing alpha compositing and transparent frames exact.
import { readFile, writeFile } from 'node:fs/promises';
import { readTokens, resolveTokens, toCss } from '@link-foundation/ui-tokens';
const { sets, diagnostics } = readTokens(await readFile('src/ui/palettes.lino', 'utf8'));
if (diagnostics.length) throw new Error(JSON.stringify(diagnostics));
const blocks = ['/* Generated by npm run build:palettes from src/ui/palettes.lino. */'];
for (const [id] of sets) {
  const light = id.endsWith('-light');
  const palette = id.replace(/-(light|dark)$/, '');
  const selector = `:root[data-skin-name='futuristic'][data-future-palette='${palette}']${light ? "[data-theme='light']" : ''}`;
  const tokens = resolveTokens(sets, id);
  if (tokens.diagnostics.length) throw new Error(JSON.stringify(tokens.diagnostics));
  // Export ordinary color tokens through the framework, and convert the
  // legacy *-rgb variables at this one boundary rather than in each skin.
  const plain = new Map([...tokens].filter(([key]) => !key.endsWith('-rgb')));
  const rgb = [...tokens]
    .filter(([key]) => key.endsWith('-rgb'))
    .map(
      ([key, token]) =>
        `  --${key}: ${['r', 'g', 'b'].map((channel) => Math.round(token.value[channel] * 255)).join(' ')};`,
    );
  blocks.push(toCss(plain, { selector }).replace(/\n}\s*$/, '\n' + rgb.join('\n') + '\n}'));
}
await writeFile('src/skins.palettes.css', blocks.join('\n\n') + '\n');
